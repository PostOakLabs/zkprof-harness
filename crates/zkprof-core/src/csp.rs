/// The csp-benchmarks fields a zkprof report cannot supply, and why.
///
/// Printed by the CLI so the gap is visible at export time rather than
/// discovered by whoever tries to submit the file.
pub const UNMAPPABLE_FIELDS: &[(&str, &str)] = &[
    (
        "verify_duration",
        "zkprof runs verification as a correctness gate outside the measured region, \
         so no report contains a verification time",
    ),
    (
        "proof_size",
        "zkprof never captures the serialised proof size",
    ),
    (
        "preprocessing_size",
        "the trusted setup is not measured, and this field is a size rather than a time",
    ),
    (
        "security_bits",
        "a declaration about the proving system, not a measurement of it; the submitter \
         must assert it (csp-benchmarks requires at least 96)",
    ),
    (
        "iop / pcs / arithm / is_zk / is_zkvm / is_pq / is_maintained / is_audited",
        "system metadata that no zkprof report carries",
    ),
];

/// Why a report could not be exported.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ExportError {
    /// The workload does not name a canonical csp-benchmarks circuit.
    UnknownTarget {
        /// The `workload_id` that could not be mapped.
        workload_id: String,
    },
    /// The report's target was rejected as a canonical circuit.
    NotACanonicalTarget {
        /// The target string that was rejected.
        target: String,
    },
    /// The report carries no usable timing, so there is no duration to report.
    NoDuration {
        /// The `workload_id` of the offending report.
        workload_id: String,
    },
}

impl std::fmt::Display for ExportError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::UnknownTarget { workload_id } => write!(
                f,
                "workload {workload_id:?} does not name a canonical csp-benchmarks circuit \
                 (expected one of {CANONICAL_TARGETS:?}); pass --target to name one explicitly, \
                 but only if this workload really is that circuit"
            ),
            Self::NotACanonicalTarget { target } => write!(
                f,
                "{target:?} is not a canonical csp-benchmarks circuit \
                 (expected one of {CANONICAL_TARGETS:?})"
            ),
            Self::NoDuration { workload_id } => write!(
                f,
                "report {workload_id:?} has no positive proving duration; \
                 there is nothing to export"
            ),
        }
    }
}

impl std::error::Error for ExportError {}

/// The `metadata` block of a csp-benchmarks result document.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct CspMetadata {
    /// RFC 3339 UTC timestamp of the run being exported.
    pub timestamp: String,
    /// Commit of the code that produced the measurement.
    pub commit_sha: String,
    /// Upstream CI run the measurement came from, when there is one.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub workflow_run_url: Option<String>,
    /// Artifacts backing the measurement.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub artifact_urls: Vec<String>,
}

impl CspMetadata {
    /// Provenance with no upstream run attached.
    #[must_use]
    pub fn new(timestamp: impl Into<String>, commit_sha: impl Into<String>) -> Self {
        Self {
            timestamp: timestamp.into(),
            commit_sha: commit_sha.into(),
            workflow_run_url: None,
            artifact_urls: Vec::new(),
        }
    }

    /// Attaches the upstream run URL.
    #[must_use]
    pub fn with_workflow_run_url(mut self, url: impl Into<String>) -> Self {
        self.workflow_run_url = Some(url.into());
        self
    }
}

/// The `systems` entry: who was measured.
///
/// Only the two fields a report actually carries are emitted. The rest exist so
/// a submitter can fill them in without reshaping the file, and are omitted
/// rather than defaulted — see [`UNMAPPABLE_FIELDS`].
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct CspSystem {
    /// e.g. `groth16`. Straight from the report.
    pub proving_system: String,
    /// e.g. `bn254`. Straight from the report.
    pub field_curve: String,
    /// Interactive oracle proof, when the submitter declares one.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub iop: Option<String>,
    /// Polynomial commitment scheme, when the submitter declares one.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub pcs: Option<String>,
    /// Arithmetisation, e.g. `R1CS`, when the submitter declares one.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub arithm: Option<String>,
    /// Whether the system is zero-knowledge, when declared.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub is_zk: Option<bool>,
    /// Whether the system is a zkVM, when declared.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub is_zkvm: Option<bool>,
    /// Claimed security level in bits. csp-benchmarks requires at least 96.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub security_bits: Option<u32>,
    /// Post-quantum, when declared.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub is_pq: Option<bool>,
    /// Still maintained, when declared.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub is_maintained: Option<bool>,
    /// Audit status, when declared.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub is_audited: Option<String>,
}

/// One row of the `measurements` array.
///
/// Durations are microseconds and sizes are bytes, matching upstream. Every
/// field except `system` and `target` is optional: an absent field means "not
/// measured", which is a different and more honest statement than zero.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct CspMeasurement {
    /// Key into the document's `systems` map.
    pub system: String,
    /// Canonical circuit, e.g. `sha256`.
    pub target: String,
    /// Input size in the target's own unit: bytes for `sha256`, field elements
    /// for `poseidon`. Absent for fixed-size targets like `ecdsa`.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub input_size: Option<u64>,
    /// Proving time in microseconds.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub proof_duration: Option<u64>,
    /// Verification time in microseconds. zkprof never measures this.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub verify_duration: Option<u64>,
    /// Serialised proof size in bytes. zkprof never captures this.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub proof_size: Option<u64>,
    /// Preprocessing artifacts in bytes. zkprof never captures this.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub preprocessing_size: Option<u64>,
    /// Constraint count, when the report carries one.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub num_constraints: Option<u64>,
    /// Peak memory in bytes, when measured.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub peak_memory: Option<u64>,
}

/// A complete csp-benchmarks result document.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct CspDocument {
    /// When and from what this was produced.
    pub metadata: CspMetadata,
    /// The systems referenced by `measurements`.
    pub systems: BTreeMap<String, CspSystem>,
    /// One row per measured (system, target, input size).
    pub measurements: Vec<CspMeasurement>,
}

/// Recognises a canonical circuit name in a zkprof `workload_id`.
///
/// The circuit must be the *leading* token, once the suite prefix `csp` is
/// stripped. So `sha256-2048` and `csp_keccak_512` are recognised, but
/// `merkle-poseidon-depth64` is not: a Merkle tree over Poseidon is a
/// different circuit from "hash N field elements", and reporting one as the
/// other would publish our duration against a workload nobody ran.
///
/// Matching a token anywhere in the id was the first cut and it is wrong in
/// the dangerous direction — it answers confidently for circuits it has never
/// seen. A workload this tool cannot place is refused, so a human names the
/// target explicitly or the export does not happen at all.
#[must_use]
pub fn detect_target(workload_id: &str) -> Option<&'static str> {
    let lower = workload_id.to_ascii_lowercase();
    let mut tokens = lower.split(['-', '_', '.']);
    let mut circuit = tokens.next()?;
    // `csp` locates the benchmark suite, not the circuit. Without this the
    // upstream harness's own ids would never resolve.
    if circuit == "csp" {
        circuit = tokens.next()?;
    }
    CANONICAL_TARGETS
        .iter()
        .copied()
        .find(|target| *target == circuit)
}

/// Converts a duration in milliseconds to whole microseconds.
///
/// Non-finite and non-positive inputs clamp to zero rather than wrapping: a
/// report with no measured time has no duration, and [`build_document`]
/// rejects it before this matters.
#[allow(clippy::cast_possible_truncation, clippy::cast_sign_loss)]
fn ms_to_us(ms: f64) -> u64 {
    if !ms.is_finite() || ms <= 0.0 {
        return 0;
    }
    (ms * 1000.0).round() as u64
}

/// Builds the `systems` entry a report can justify.
#[must_use]
fn build_system(report: &Report) -> CspSystem {
    CspSystem {
        proving_system: report.system.proof_system.clone(),
        field_curve: report.system.curve_or_field.clone(),
        ..CspSystem::default()
    }
}

/// Turns one report into one `measurements` row.
///
/// # Errors
///
/// - [`ExportError::NoDuration`] if the report has no positive proving time.
pub fn build_measurement(
    system: &str,
    target: &str,
    report: &Report,
    input_size: Option<u64>,
) -> Result<CspMeasurement, ExportError> {
    let iterations = report.iterations.max(1);
    let per_proof_ms = report.total_ms / f64::from(iterations);
    let proof_duration = ms_to_us(per_proof_ms);
    if proof_duration == 0 {
        return Err(ExportError::NoDuration {
            workload_id: report.workload_id.clone(),
        });
    }

    Ok(CspMeasurement {
        system: system.to_owned(),
        target: target.to_owned(),
        input_size,
        proof_duration: Some(proof_duration),
        // Deliberately absent: see UNMAPPABLE_FIELDS.
        verify_duration: None,
        proof_size: None,
        preprocessing_size: None,
        num_constraints: report.system.constraint_count,
        peak_memory: report.memory.peak_heap_bytes,
    })
}

/// Builds a whole result document from one or more reports.
///
/// `system` is the key the measurements are published under, and also the name
/// that appears in `systems`. `target` must be a canonical circuit — callers
/// should pass what [`detect_target`] returned, or an explicit override that a
/// human has checked.
///
/// # Errors
///
/// - [`ExportError::NotACanonicalTarget`] if `target` is not canonical.
/// - [`ExportError::NoDuration`] if any report has no positive proving time.
pub fn build_document(
    system: &str,
    target: &str,
    metadata: CspMetadata,
    entries: &[(&Report, Option<u64>)],
) -> Result<CspDocument, ExportError> {
    if !CANONICAL_TARGETS.contains(&target) {
        return Err(ExportError::NotACanonicalTarget {
            target: target.to_owned(),
        });
    }

    let mut measurements = Vec::with_capacity(entries.len());
    for (report, input_size) in entries {
        measurements.push(build_measurement(system, target, report, *input_size)?);
    }

    let first = entries
        .first()
        .map(|(report, _)| *report)
        .ok_or(ExportError::NoDuration {
            workload_id: "(no reports)".to_owned(),
        })?;

    let mut systems = BTreeMap::new();
    systems.insert(system.to_owned(), build_system(first));

    Ok(CspDocument {
        metadata,
        systems,
        measurements,
    })
}

/// Formats an instant as an RFC 3339 UTC timestamp, e.g.
/// `2026-08-30T18:52:03Z`.
///
/// Implemented here rather than pulled in as a dependency: the only thing this
/// crate needs is "the current time, in a format upstream accepts", and a
/// date/time crate is a large dependency for one string. The conversion from
/// days-since-epoch to a civil date is Howard Hinnant's
/// `civil_from_days`, which is exact for the whole `i64` range.
#[must_use]
pub fn rfc3339_utc(now: SystemTime) -> String {
    let secs = now.duration_since(UNIX_EPOCH).map_or(0, |d| d.as_secs());
    let days = i64::try_from(secs / 86_400).unwrap_or(i64::MAX);
    let sod = secs % 86_400;
    let (year, month, day) = civil_from_days(days);
    format!(
        "{:04}-{:02}-{:02}T{:02}:{:02}:{:02}Z",
        year,
        month,
        day,
        sod / 3600,
        (sod % 3600) / 60,
        sod % 60
    )
}

/// Days since 1970-01-01 to a `(year, month, day)` civil date.
///
/// Howard Hinnant's algorithm; see
/// <https://howardhinnant.github.io/date_algorithms.html#civil_from_days>.
#[allow(clippy::cast_possible_truncation, clippy::cast_sign_loss)]
fn civil_from_days(days: i64) -> (i64, u32, u32) {
    let z = days + 719_468;
    let era = if z >= 0 { z } else { z - 146_096 } / 146_097;
    let doe = i64::from(u32::try_from(z - era * 146_097).unwrap_or(0)); // [0, 146096]
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365; // [0, 399]
    let y = yoe + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100); // [0, 365]
    let mp = (5 * doy + 2) / 153; // [0, 11]
    let d = doy - (153 * mp + 2) / 5 + 1; // [1, 31]
    let m = if mp < 10 { mp + 3 } else { mp - 9 }; // [1, 12]
    (
        if m <= 2 { y + 1 } else { y },
        u32::try_from(m).unwrap_or(1),
        u32::try_from(d).unwrap_or(1),
    )
}
