//! The `csp-benchmarks` result shape, and the honest subset of it a zkprof
//! report can fill.
//!
//! `csp-benchmarks` is the client-side-proving benchmark harness whose results
//! are published quarterly on ethproofs.org. It was originally under
//! `privacy-ethereum/` and now lives at `ethereum/csp-benchmarks`; the
//! `workflow_run_url` values in their own result files still carry the old
//! owner, so both spellings refer to the same project.
//!
//! Shape pinned 2026-08-30 to upstream commit
//! `993afae38287f97a1cea3ae47d39c6786d1a30ee` ("Add BLAKE3 benchmarks across
//! proving systems (#301)", 2026-08-20), read from
//! `results/collected_benchmarks_28227311138.json`,
//! `utils/src/harness.rs` and `utils/src/metadata.rs`.
//!
//! # What maps, and what deliberately does not
//!
//! A zkprof report is a *timing attribution* document. A csp-benchmarks result
//! is a *system capability* record. They overlap in the middle and not at the
//! edges, and the overlap is smaller than it first looks:
//!
//! | csp field | from a zkprof report | note |
//! |---|---|---|
//! | `proof_duration` | `total_ms / iterations`, as µs | the measured region is the proving loop only |
//! | `num_constraints` | `system.constraint_count` | |
//! | `peak_memory` | `memory.peak_heap_bytes` | measured on wasm; absent natively |
//! | `verify_duration` | — | zkprof runs verification as a correctness gate *outside* the measured region |
//! | `proof_size` | — | never captured |
//! | `preprocessing_size` | — | trusted setup is not measured, and this is a size, not a time |
//! | `iop` / `pcs` / `arithm` / `security_bits` / `is_zk` / `is_audited` … | — | declarations about the system, not measurements of it |
//!
//! The last group is the one that matters most for honesty. csp-benchmarks
//! admits only systems with at least 96 bits of security, and asks
//! contributors to assert `security_bits` for their own system. zkprof does not
//! know that number — it measures time — so the exporter omits it rather than
//! guessing. Supplying it is the submitter's job, and it is exactly the kind of
//! claim that must not be generated by a tool.
//!
//! Fields a report cannot supply are **omitted from the JSON entirely**, never
//! emitted as 0. A zero in `proof_size` is a claim that the proof is empty, and
//! a reader cannot tell it apart from "not measured". See [`UNMAPPABLE_FIELDS`].
//!
//! # Workload identity
//!
//! csp-benchmarks measures canonical circuits. Our default workload is
//! Merkle-Poseidon, which is *not* one of them, so [`build_document`] refuses a
//! target it cannot map unless the caller names one explicitly. Approximating
//! "merkle-poseidon, depth 64" as "poseidon, input_size 64" would publish a
//! number against a circuit nobody ran.

